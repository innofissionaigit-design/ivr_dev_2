def _script(s: str) -> str:
    if any("ऀ" <= c <= "ॿ" for c in s):
        return "hi"
    if any("ঀ" <= c <= "৿" for c in s):
        return "bn"
    return "latin"


def _tables(script: str):
    return {
        "latin": (_LATIN_SWAP, _LATIN_OOC, _LATIN_VOW),
        "bn": (_BN_SWAP, _BN_OOC, _BN_VOW),
        "hi": (_HI_SWAP, _HI_OOC, _HI_VOW),
    }[script]


def _replace_one(s: str, table: dict, rng: random.Random) -> str | None:
    spots = [i for i, c in enumerate(s) if c.lower() in table]
    if not spots:
        return None
    i = rng.choice(spots)
    options = table[s[i].lower()]
    return s[:i] + (rng.choice(options) if options else "") + s[i + 1 :]


def variants(form: str, rng: random.Random) -> dict[str, list[str]]:
    """A few spoken variants of one form, per family. Empty where a rule has nothing to act on."""
    script = _script(form)
    swap, ooc, vow = _tables(script)
    base = normalise(form, frozenset(TITLES))
    out: dict[str, list[str]] = {f: [] for f in FAMILIES}
    for _ in range(3):
        v = _replace_one(base, swap, rng)
        if v and v != base:
            out["in_class"].append(v)
        v = _replace_one(base, ooc, rng)
        if v and v != base:
            out["out_of_class"].append(v)
        v = _replace_one(base, vow, rng)
        if v and v != base:
            out["vowel"].append(v)
    if script == "latin" and len(base) >= 4:
        out["vowel"].append(
            base.replace("ee", "i").replace("oo", "u") if ("ee" in base or "oo" in base) else base + base[-1]
        )
        cons = [i for i, c in enumerate(base) if c.isalpha() and c not in "aeiou"]
        if cons:
            i = rng.choice(cons)
            out["drop_insert"].append(base[:i] + base[i + 1 :])
            out["drop_insert"].append(base[:i] + base[i] + "a" + base[i:] if i else base + "a")
    elif len(base) >= 4:
        i = rng.randrange(1, len(base) - 1)
        out["drop_insert"].append(base[:i] + base[i + 1 :])
    if len(base) >= 4:
        j = rng.randrange(0, len(base) - 1)
        out["spelling"].append(base[:j] + base[j + 1] + base[j] + base[j + 2 :])
        out["spelling"].append(base[:j] + rng.choice("xqz" if script == "latin" else "কমন") + base[j + 1 :])
    return {k: [x for x in dict.fromkeys(v) if x and x != base] for k, v in out.items()}


