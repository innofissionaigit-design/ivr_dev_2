"""Entity F-score and match latency of the phonetic gazetteer against the linear scan it replaces (KCD-096).

    python tools/gazetteer_eval.py                       # the seeded catalogue (needs no server)
    python tools/gazetteer_eval.py --catalogue cat.json  # a saved GET /api/v1/catalogue
    python tools/gazetteer_eval.py --sizes 74,1000,10000,50000

WHAT IS MEASURED
  * A "mispronunciation bucket": for every doctor surname and test name/alias in the catalogue, spoken variants
    generated by rules, in Latin, Bengali and Devanagari script. Four families, kept apart so a weakness in one is
    not averaged away:
        in_class     a consonant swapped for one in the same sound class (b/p, d/t, sh/s, aspirated/plain)
        vowel        vowel quality drift and doubled/undoubled letters
        drop_insert  a consonant dropped or an extra one inserted
        out_of_class a confusion the fold does NOT model (k/t, r/l, m/b): where sound folding cannot help
    plus a spelling-noise family (transposition, one stray letter) that stresses the spelling tier.
  * A negative bucket: nonsense strings and plausible names that are NOT in the catalogue. Nothing should be
    suggested; anything suggested is a false suggestion.
  * Scoring, per query: the top-3 suggestions are compared with the one right entity. True positive = right entity
    listed; every OTHER listed entity is a false positive (a wrong name read back to the caller costs a turn and
    can lead a caller to say "yes" to the wrong one). precision, recall and F1 are over the whole bucket.

WHAT THIS DOES NOT PROVE. The variants are GENERATED, and the generator shares its notion of "same sound class"
with the fold under test, so `in_class` flatters it; `out_of_class` and the spelling family are there to show the
other side. The numbers are a regression harness and a comparison of two algorithms on the same synthetic input.
They are not an estimate of how a real caller is understood: that needs real Bengali/Hindi/English call
transcripts, which the repository does not have (docs/pod-verification-checklist.md).
"""

