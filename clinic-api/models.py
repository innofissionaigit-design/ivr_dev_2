class ComplaintRecord(Base):
    """Ported story "Caller wants to make a complaint" (agent/complaint.py).

    Acceptance criterion 3 is that the complaint is captured VERBATIM, which sits
    against this system's rule that caller free text never reaches `logs/` or the
    call record (agent/call_record.py keeps counts, flags and ids, "never any
    text"). Both hold at once because the verbatim text goes to exactly one
    narrow-access durable store -- this table -- while the escalation ledger and
    the call record keep carrying only the reason code. `CallbackRequest.call_summary`
    above already established that precedent in this schema.

    `text` is the caller's own words as the recogniser produced them, unedited and
    never an LLM paraphrase: a complaint summarised by a model is no longer the
    complaint that was made, and criterion 5 (never explain it away) starts with
    not rewriting it.

    `status` tracks the human side of the promise, the same placeholder discipline
    as CallbackRequest: this repository cannot transfer a SIP leg, so "routed to a
    person" means an actionable queue row, and the table says plainly which rows
    have actually been dealt with rather than implying every one was.
    """

    __tablename__ = "complaints"
    id = Column(Integer, primary_key=True)
    call_id = Column(String, nullable=False, index=True)
    # The caller's words, exactly as transcribed. Nullable=False with a "" default
    # rather than optional: a complaint row with no text is a bug, not a state.
    text = Column(Text, nullable=False, default="")
    # Which phrase family detected it ("en" | "latin" | "bn" | "hi") -- the same
    # tag agent/complaint.detect_complaint() returns, kept for auditing the
    # detector's real-world hit rate per language, never used to pick a reply.
    detected_by = Column(String, nullable=False, default="")
    # The language the call was being conducted in when the complaint was filed.
    lang = Column(String, nullable=False, default="")
    phone = Column(String, nullable=True)
    status = Column(String, nullable=False, default="open")  # open | acknowledged | closed
    created_at = Column(DateTime, nullable=False)
